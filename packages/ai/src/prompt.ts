import type { ChapterInput } from "./input";
import type { Prompt } from "./writer";


// Границы проверки ответа. Модель недобирает объём на 10–20 %, поэтому просим больше, чем требуем: главы по 1000–1200 знаков её отклоняли
export const PROSE_LIMITS = { minParagraphs: 3, maxParagraphs: 5, minChars: 900, maxChars: 2500 } as const;
const PROSE_ASKED_CHARS = { min: 1400, max: 2200 } as const;
export const SCENARIO_FIELD_MAX_CHARS = 700;

const RULES = [
  "Ты — редактор сервиса самопознания «Твой оракул». Тебе дают описание части матрицы судьбы, арканы в этой части и готовые тексты о них.",
  "Задача: связать готовые тексты в цельную главу разбора для одного человека. Опирайся только на данные: не добавляй фактов, историй, чисел и значений арканов, которых нет во входе.",
  "Пиши по-русски, на «вы», как гипотезы для размышления: «может», «часто», «возможно». Это не предсказание и не консультация. Не используй слова-связки: «стоит заметить», «важно отметить», «таким образом», «важно помнить».",
  "Нейтральный род: не используй окончания, выдающие пол читателя. Вместо «вы уверена» — «вам хватает уверенности», вместо «вы устал» — «накапливается усталость».",
  "Нельзя: предсказывать будущее, называть сроки и события, обещать доход или отношения; упоминать диагнозы, болезни, лечение; пугать кармой, порчей, расплатой.",
];

export const NEUTRAL_GENDER_RULE = RULES[3]!;
export const FORBIDDEN_RULE = RULES[4]!;

const NAMING_RULE = "Называй арканы по номеру и названию, как во входе.";

// Главы модель пишет обычным текстом: в JSON её собственные кавычки ломали разбор ответа
const PROSE_ANSWER = [
  `${NAMING_RULE} Ответ — только текст главы: без заголовков, списков, Markdown, JSON и пояснений.`,
  "Готовые тексты — материал, а не глава. Не копируй из них предложения и не пересказывай бесплатную страницу аркана. Напиши, как эти арканы работают вместе в этой позиции: что из этого следует для человека, чего нет ни на одной отдельной странице.",
  "Если у аркана есть поле seen, этот блок уже был в названной там роли. Не повторяй его. Одно предложение, что образ уже разобран в той роли, и дальше только то, чем эта роль отличается.",
  `Формат: ${PROSE_LIMITS.minParagraphs}–${PROSE_LIMITS.maxParagraphs} абзацев, между абзацами пустая строка, вместе ${PROSE_ASKED_CHARS.min}–${PROSE_ASKED_CHARS.max} знаков. Первый абзац — что показывает эта часть матрицы именно у этого человека; дальше — как арканы проявляются вместе, где ресурс и где перекос; последний — что с этим можно делать. Последний абзац не пересказывает главу.`,
].join("\n\n");

const SCENARIO_ANSWER = [
  `${NAMING_RULE} Ответ — только JSON-объект по схеме ниже, без пояснений и без Markdown.`,
  `Схема ответа:
{"pattern": "…", "tension": "…", "resource": "…", "blindSpot": "…", "turningPoint": "…", "experiment": "…", "question": "…?"}
Это итог разбора по методике ORACLE. pattern — сценарий, который может повторяться; tension — где в нём напряжение; resource — на что опереться; blindSpot — что легко не замечать; turningPoint — где можно изменить ход сценария; experiment — одна строка из трёх частей: час цифрами (например 21:00), место (за столом, в блокноте, на кухне, в дневнике) и действие. Образец целиком: «Каждый вечер в 21:00 за столом запишите одну строку о том, где сегодня сдержались». Без часа и места ответ отклонят. Не пишите «одно небольшое действие» и «семь дней подряд — одно»; question — один вопрос для себя, заканчивается знаком «?».
Каждое поле — 1–4 предложения, не больше ${SCENARIO_FIELD_MAX_CHARS} знаков. Поле previous — начала уже написанных глав: не противоречь им и не повторяй их дословно. Если глава уже назвала ресурс, не называй его перекосом.`,
].join("\n\n");

const RETRY_HINTS: Record<string, string> = {
  length: "Прошлый ответ отклонён по объёму: выдержи число абзацев и знаков из формата.",
  stop_words: "Прошлый ответ отклонён: в нём были обороты-предсказания. Пиши только как гипотезы для размышления.",
  schema: "Прошлый ответ отклонён: он не соответствует схеме. Для итоговой главы верни только JSON, для остальных — текст абзацами.",
  not_json: "Прошлый ответ отклонён: итоговая глава должна быть JSON по схеме.",
  filler: "Прошлый ответ отклонён: в нём были слова-связки («стоит заметить», «таким образом», «важно помнить»). Пиши сразу по сути.",
  vague: "Прошлый ответ отклонён: в experiment не было часа и места. Перепиши experiment одной строкой: «Каждый вечер в 21:00 за столом запишите одну строку …» — с цифрами часа и местом.",
  repeat: "Прошлый ответ отклонён: он повторяет готовый текст почти дословно. Перескажи своими словами, что эти арканы дают вместе, и не копируй фразы из входа.",
};

export function buildPrompt(input: ChapterInput, retryAfter?: string): Prompt {
  const answer = input.chapter === "scenario" ? SCENARIO_ANSWER : PROSE_ANSWER;
  const hint = retryAfter ? RETRY_HINTS[retryAfter] : undefined;
  return { system: [...RULES, answer, ...(hint ? [hint] : [])].join("\n\n"), user: JSON.stringify(input) };
}
