import type { ChapterInput } from "./input";
import type { Prompt } from "./writer";

export const PROSE_LIMITS = { minParagraphs: 3, maxParagraphs: 5, minChars: 1200, maxChars: 2500 } as const;
export const SCENARIO_FIELD_MAX_CHARS = 700;

const RULES = [
  "Ты — редактор сервиса самопознания «Твой оракул». Тебе дают описание части матрицы судьбы, арканы в этой части и готовые тексты о них.",
  "Задача: связать готовые тексты в цельную главу разбора для одного человека. Опирайся только на данные: не добавляй фактов, историй, чисел и значений арканов, которых нет во входе.",
  "Пиши по-русски, на «вы», как гипотезы для размышления: «может», «часто», «стоит заметить». Это не предсказание и не консультация.",
  "Нейтральный род: не используй окончания, выдающие пол читателя. Вместо «вы уверена» — «вам хватает уверенности», вместо «вы устал» — «накапливается усталость».",
  "Нельзя: предсказывать будущее, называть сроки и события, обещать доход или отношения; упоминать диагнозы, болезни, лечение; пугать кармой, порчей, расплатой.",
];

const NAMING_RULE = "Называй арканы по номеру и названию, как во входе.";

// Главы модель пишет обычным текстом: в JSON её собственные кавычки ломали разбор ответа
const PROSE_ANSWER = [
  `${NAMING_RULE} Ответ — только текст главы: без заголовков, списков, Markdown, JSON и пояснений.`,
  `Формат: ${PROSE_LIMITS.minParagraphs}–${PROSE_LIMITS.maxParagraphs} абзацев, между абзацами пустая строка, вместе ${PROSE_LIMITS.minChars}–${PROSE_LIMITS.maxChars} знаков. Первый абзац — что показывает эта часть матрицы именно у этого человека; дальше — как арканы проявляются вместе, где ресурс и где перекос; последний — что с этим можно делать.`,
].join("\n\n");

const SCENARIO_ANSWER = [
  `${NAMING_RULE} Ответ — только JSON-объект по схеме ниже, без пояснений и без Markdown.`,
  `Схема ответа:
{"pattern": "…", "tension": "…", "resource": "…", "blindSpot": "…", "turningPoint": "…", "experiment": "…", "question": "…?"}
Это итог разбора по методике ORACLE. pattern — сценарий, который может повторяться; tension — где в нём напряжение; resource — на что опереться; blindSpot — что легко не замечать; turningPoint — где можно изменить ход сценария; experiment — одно конкретное небольшое действие на 7 дней; question — один вопрос для себя, заканчивается знаком «?».
Каждое поле — 1–4 предложения, не больше ${SCENARIO_FIELD_MAX_CHARS} знаков. Поле previous во входе — начала уже написанных глав: опирайся на них и не повторяй их дословно.`,
].join("\n\n");

export function buildPrompt(input: ChapterInput): Prompt {
  const answer = input.chapter === "scenario" ? SCENARIO_ANSWER : PROSE_ANSWER;
  return { system: [...RULES, answer].join("\n\n"), user: JSON.stringify(input) };
}
