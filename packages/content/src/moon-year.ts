const SAMPLE_ITEM: MoonItem = { label: "9 ноября, 10:02", signLocative: "в Скорпионе" };
const SAMPLE_EVENTS: YearEventFacts[] = [
  { label: "3 января, 13:03", super: true },
  { label: "1 февраля, 01:09", super: false },
];

export function checkMoonExtraTexts(): string[] {
  const sampleYear = (kind: YearKind): YearFacts => ({ year: 2026, kind, events: SAMPLE_EVENTS, supermoonKm: 360_000 });
  return findViolations([
    { id: "month summary", fields: [monthSummary({ monthLocative: "ноябре", year: 2026, new: [SAMPLE_ITEM], full: [SAMPLE_ITEM], signChanges: 12 })] },
    { id: "natal note", fields: [NATAL_MOON_NOTE] },
    ...(["new", "full"] as const).flatMap((kind) => [
      { id: `${kind} intro`, fields: [yearIntro(kind, 2026)] },
      ...yearFaq(sampleYear(kind)).map((item, index) => ({ id: `${kind} faq ${index + 1}`, fields: [item.question, item.answer] })),
    ]),
    { id: "key points", fields: [KEY_POINTS_TITLE, KEY_POINTS_NOTE, ...Object.values(KEY_POINT_ASTRONOMY), ...Object.values(SIGN_SYMBOLS), ...Object.values(NEW_MOON_QUESTIONS), ...Object.values(FULL_MOON_QUESTIONS)] },
    { id: "daily guide", fields: [DAILY_GUIDE.intro, ...DAILY_GUIDE.items] },
    ...MONTH_FAQ_EXTRA.map((item, index) => ({ id: `month faq extra ${index + 1}`, fields: [item.question, item.answer] })),
    { id: "phases intro", fields: [PHASES_INTRO] },
    ...PHASES_FAQ.map((item, index) => ({ id: `phases faq ${index + 1}`, fields: [item.question, item.answer] })),
  ]);
}
