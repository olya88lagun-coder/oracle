const PLURAL: Record<YearKind, string> = { new: "новолуний", full: "полнолуний" };

export function yearIntro(kind: YearKind, year: number): string {
  if (kind === "new") {
    return `Новолуние — момент, когда Луна проходит между Землёй и Солнцем и повёрнута к нам неосвещённой стороной: диск не виден, а лунный месяц начинается заново. Ниже — все новолуния ${year} года с точным временем по Москве, знаком зодиака, в котором стояла Луна, и расстоянием до Земли.`;
  }
  return `Полнолуние — момент, когда Земля оказывается между Луной и Солнцем и мы видим полностью освещённый диск. Ниже — все полнолуния ${year} года с точным временем по Москве, знаком зодиака, в котором стояла Луна, и расстоянием до Земли.`;
}

// В году бывает 12 или 13 новолуний и полнолуний, поэтому родительный падеж множественного числа один для обоих случаев
export function yearFaq(facts: YearFacts): { question: string; answer: string }[] {
  const { year, kind, events } = facts;
  const plural = PLURAL[kind];
  const supers = events.filter((event) => event.super).map((event) => event.label);
  const list = [
    { question: `Сколько ${plural} в ${year} году?`, answer: `В ${year} году ${events.length} ${plural}: ${events.map((event) => event.label).join("; ")}. ${TIME_NOTE}` },
    ...(kind === "full"
      ? [
          {
            question: "Что такое суперлуние?",
            answer: `Суперлуние — полнолуние, когда Луна находится близко к Земле. Орбита Луны вытянута, поэтому расстояние до неё меняется примерно от 357 до 406 тысяч километров, и в ближней точке диск выглядит чуть крупнее. Единого определения у астрономов нет: на этой странице суперлунием названо полнолуние, когда Луна ближе ${facts.supermoonKm.toLocaleString("ru-RU")} км. ${supers.length ? `В ${year} году такие полнолуния: ${supers.join("; ")}.` : `В ${year} году таких полнолуний нет.`}`,
          },
        ]
      : []),
    {
      question: kind === "new" ? "Чем новолуние отличается от полнолуния?" : "Чем полнолуние отличается от новолуния?",
      answer: "В новолуние Луна находится между Землёй и Солнцем и не видна: к нам повёрнута её неосвещённая сторона. В полнолуние Земля находится между Луной и Солнцем, и диск освещён целиком. От одного новолуния до следующего проходит около 29,5 суток.",
    },
    { question: "Почему время указано по Москве?", answer: `Фаза Луны наступает в один и тот же момент для всей Земли, различается только местное время на часах. ${TIME_NOTE}` },
  ];
  return list;
}

