export type YearKind = "new" | "full";
// label — «9 ноября, 10:02» по Москве; signLocative — «в Скорпионе»
export type MoonItem = { label: string; signLocative: string };
export type MonthSummaryFacts = { monthLocative: string; year: number; new: MoonItem[]; full: MoonItem[]; signChanges: number };
// super — полнолуние ближе порога суперлуния
export type YearEventFacts = { label: string; super: boolean };
export type YearFacts = { year: number; kind: YearKind; events: YearEventFacts[]; supermoonKm: number };

const TIME_NOTE = "Время указано по Москве (UTC+3); в другом городе оно сдвигается на разницу часовых поясов.";

// Знак назван на момент фазы: в сетке календаря знак стоит на полдень, и в день смены знака они могут различаться
const describe = (items: MoonItem[]) => items.map((item) => `${item.label} (в этот момент Луна ${item.signLocative})`).join(" и ");

// Одно предложение с датами и знаками главных фаз месяца и одно про переходы Луны в новые знаки; события, которых нет в месяце, пропускаем
export function monthSummary(facts: MonthSummaryFacts): string {
  const parts = [facts.new.length ? `новолуние — ${describe(facts.new)}` : "", facts.full.length ? `полнолуние — ${describe(facts.full)}` : ""].filter(Boolean);
  const lead = parts.length ? `В ${facts.monthLocative} ${facts.year} года ${parts.join("; ")}. Время по Москве.` : `В ${facts.monthLocative} ${facts.year} года нет ни новолуния, ни полнолуния: они приходятся на соседние месяцы.`;
  return `${lead} За месяц Луна ${facts.signChanges} раз переходит в новый знак зодиака: время каждого перехода — на ленте знаков.`;
}

