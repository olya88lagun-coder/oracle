import Link from "next/link";
import { LILA_GAME_PATH } from "@/lib/lila-paths";

const REPHRASE: readonly (readonly [string, string])[] = [
  ["«Как мне жить?»", "«Что для меня сейчас важнее всего?»"],
  ["«Будет ли у меня успех?»", "«Что для меня значит успех и что мне мешает к нему идти?»"],
  ["«Почему он так поступил?»", "«Что я чувствую, когда он так поступает?»"],
  ["«Что со мной не так?»", "«Что во мне сейчас просит внимания?»"],
];

export function LilaIntention() {
  return (
    <>
      <p>
        Намерение — это личный вопрос, с которым вы идёте по полю Лилы. От формулировки зависит, насколько ответы клеток будут для вас «про
        вас».
      </p>

      <h2>Что делает намерение хорошим</h2>
      <ul>
        <li>
          <strong>Личное.</strong> Вопрос о вас и вашем опыте, а не о других людях: «Что мешает мне…», а не «Почему он…».
        </li>
        <li>
          <strong>Конкретное.</strong> Одна область жизни, а не «всё сразу».
        </li>
        <li>
          <strong>Открытое.</strong> Вопрос начинается с «что», «как», «почему», а не с «да» или «нет».
        </li>
        <li>
          <strong>Честное.</strong> Вы готовы услышать неудобный ответ.
        </li>
      </ul>

      <h2>Примеры удачных формулировок</h2>
      <ul>
        <li>
          <strong>Отношения:</strong> «Что мешает мне говорить близким о своих чувствах?»; «Чего я жду от отношений и чего боюсь?»
        </li>
        <li>
          <strong>Работа:</strong> «Почему мне трудно принять решение о работе?»; «Что для меня важно в деле, которым я занимаюсь?»
        </li>
        <li>
          <strong>Деньги:</strong> «Что происходит со мной, когда я думаю о деньгах?»; «Что мешает мне двигаться в вопросе денег?»
        </li>
        <li>
          <strong>Выбор:</strong> «Что мне важно учесть перед решением, которое я откладываю?»
        </li>
        <li>
          <strong>Перемены:</strong> «Что я боюсь потерять, если изменю привычный порядок?»
        </li>
        <li>
          <strong>О себе:</strong> «Что во мне сейчас просит внимания?»
        </li>
      </ul>

      <h2>Что лучше переформулировать</h2>
      <div className="blog-table-wrap">
        <table className="blog-table">
          <caption>Как сделать намерение точнее</caption>
          <thead>
            <tr>
              <th scope="col">Размытое</th>
              <th scope="col">Лучше</th>
            </tr>
          </thead>
          <tbody>
            {REPHRASE.map(([vague, better]) => (
              <tr key={vague}>
                <td>{vague}</td>
                <td>{better}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <p>
        Вопросы о будущем («Сбудется ли…», «Получится ли…») в Лиле не работают: игра не предсказывает события, она помогает понять, что вы
        думаете и чувствуете о своей ситуации.
      </p>

      <h2>Сколько времени уделить</h2>
      <p>
        Три-пять минут на формулировку — достаточно. Если вопрос не приходит, выберите готовую тему на странице игры («Отношения», «Работа»,
        «Выбор», «Деньги», «Перемены», «О себе») и подправьте формулировку под себя.
      </p>

      <h2>Что делать с намерением во время игры</h2>
      <p>
        Возвращайтесь к вопросу на каждом ходу: «Как клетка связана с моим намерением?». Записывайте короткие мысли. В конце партии
        перечитайте записи подряд: повторяющиеся слова и темы часто показывают главное.
      </p>
      <p>
        <Link className="button button--lavender" href={LILA_GAME_PATH}>
          Играть
        </Link>
      </p>
    </>
  );
}
