const one = (value: string | undefined): PositionText => ({ list: false, lines: value ? [value] : [] });

// Часть карты, подходящая позиции: у сути — абзац про главную тему, у ресурса и перекоса — три пункта списком
export function positionReading(card: TarotCard, source: SpreadSource): PositionText {
  switch (source) {
    case "essence":
      return one(card.essence[1] ?? card.essence[0]);
    case "love":
      return one(card.love[0]);
    case "money":
      return one(card.money[0]);
    case "resource":
      return { list: true, lines: [...card.resource] };
    case "distortion":
      return { list: true, lines: [...card.distortion] };
    case "day":
      return one(card.day.join(" "));
    case "action":
      return one(card.action);
    case "question":
      return one(card.question);
  }
}

// Карты в одном раскладе не повторяются: каждая следующая выбирается из оставшихся
export function pickDistinctIndexes(count: number, deckSize: number, random?: () => number): number[] {
  if (count > deckSize) throw new Error("В колоде не хватает карт для расклада");
  const pool = Array.from({ length: deckSize }, (_, index) => index);
  const picked: number[] = [];
  for (let step = 0; step < count; step += 1) {
    const [index] = pool.splice(pickCardIndex(pool.length, random), 1);
    picked.push(index!);
  }
  return picked;
}
